import React, { useState } from 'react';
import {
  MessageSquareText,
  Send,
  Sparkles,
  Database,
  Code,
  ShieldCheck,
  CheckCircle2,
  Trash2,
  HelpCircle,
  TrendingDown,
  Layers,
  ArrowRight,
} from 'lucide-react';
import { useProduct } from '../context/ProductContext';

interface ChatMessage {
  id: string;
  sender: 'user' | 'assistant';
  timestamp: string;
  text: string;
  language?: 'English' | 'Roman Urdu';
  tableData?: {
    headers: string[];
    rows: (string | number)[][];
  };
  sqlQuery?: string;
  sourceDataset?: string;
  explanation?: string;
  reliabilityScore?: number;
}

export const AiAssistantModule: React.FC = () => {
  const { products, customers, sales, metrics, addAuditLog } = useProduct();
  const [inputText, setInputText] = useState('');
  const [isProcessing, setIsProcessing] = useState(false);

  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      id: 'msg-init-1',
      sender: 'assistant',
      timestamp: 'Today at 08:00 AM',
      text: 'Salam! I am DistributionIQ AI Analytics Assistant. You can ask me commercial, inventory, and data quality questions in plain English or Roman Urdu.',
      explanation: 'Grounded against normalized PostgreSQL database tables with SQLGlot AST read-only enforcement.',
      reliabilityScore: 98,
    },
  ]);

  const SAMPLE_QUESTIONS = [
    { text: 'Pichlay 30 din mein sab se zyada sales kis product ki hui?', lang: 'Roman Urdu' },
    { text: 'Which products are at critical stockout risk?', lang: 'English' },
    { text: 'Kis customer ke orders kam ho rahay hain?', lang: 'Roman Urdu' },
    { text: 'Top 5 wholesale customers by total spend', lang: 'English' },
    { text: 'Meri sales pichlay month se kitni zyada hui hain?', lang: 'Roman Urdu' },
    { text: 'What is the financial impact of duplicate invoices?', lang: 'English' },
  ];

  const handleSend = (queryText?: string) => {
    const textToSend = queryText || inputText;
    if (!textToSend.trim()) return;

    const userMsg: ChatMessage = {
      id: `msg-${Date.now()}-u`,
      sender: 'user',
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      text: textToSend,
    };

    setMessages((prev) => [...prev, userMsg]);
    if (!queryText) setInputText('');
    setIsProcessing(true);

    setTimeout(() => {
      const lower = textToSend.toLowerCase();
      let response: ChatMessage;

      // Question 1: Top sales in Roman Urdu / English
      if (
        lower.includes('sab se zyada') ||
        lower.includes('top sales') ||
        lower.includes('highest sales') ||
        lower.includes('pichlay 30 din mein sab se zyada')
      ) {
        response = {
          id: `msg-${Date.now()}-a`,
          sender: 'assistant',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          language: lower.includes('sab se') ? 'Roman Urdu' : 'English',
          text: lower.includes('sab se')
            ? 'Pichlay 30 din mein sab se zyada revenue "Gourmet Cola 1.5L" aur "Sufi Sunflower Cooking Oil" se generate hui hai. Nichey top 3 products ka verified data mojood hai:'
            : 'Over the last 30 days, the highest wholesale revenue was generated by Gourmet Cola 1.5L and Sufi Sunflower Cooking Oil. Below are the verified figures:',
          tableData: {
            headers: ['Product Name', 'SKU', 'Units Sold', 'Total Revenue (PKR)', 'Category'],
            rows: [
              ['Gourmet Cola 1.5L (Pack of 6)', 'SKU-BEV-101', '840 Cartons', 'PKR 823,200', 'Beverages'],
              ['Sufi Sunflower Cooking Oil 5L', 'SKU-OIL-202', '540 Cans', 'PKR 1,609,200', 'Edible Oils'],
              ["Olper's Milk 1L (Pack of 12)", 'SKU-DAI-303', '1,050 Cartons', 'PKR 3,622,500', 'Dairy & UHT'],
            ],
          },
          sqlQuery: `SELECT p.name, p.sku, SUM(s.quantity) AS units_sold, SUM(s.total_revenue) AS revenue
FROM trusted_sales s
JOIN products_catalog p ON s.sku = p.sku
WHERE s.date >= CURRENT_DATE - INTERVAL '30 days' AND s.status != 'Quarantined'
GROUP BY p.name, p.sku
ORDER BY revenue DESC LIMIT 3;`,
          sourceDataset: 'trusted_sales (PostgreSQL schema v2.1)',
          explanation:
            'Query excludes quarantined duplicate batches (INV-2026-9281) to ensure accurate commercial reporting.',
          reliabilityScore: 99,
        };
      }
      // Question 2: Stockout / Khatam honay wala
      else if (
        lower.includes('stockout') ||
        lower.includes('khatam') ||
        lower.includes('out of stock') ||
        lower.includes('stock kam')
      ) {
        response = {
          id: `msg-${Date.now()}-a`,
          sender: 'assistant',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          language: lower.includes('khatam') || lower.includes('kam') ? 'Roman Urdu' : 'English',
          text: lower.includes('khatam')
            ? 'Warehouse mein 2 products ka stock intehai kam hai aur 4-5 din mein khatam honay ka khatra hai:'
            : 'Two critical products are currently at severe stockout risk with depletion estimated within 4 to 5 days:',
          tableData: {
            headers: ['Product', 'Current Stock', 'Daily Demand', 'Est. Days Left', 'Supplier Lead Time'],
            rows: [
              ['Gourmet Cola 1.5L', '120 Cartons', '28/day', '~4.2 Days', '14 Days (Delayed)'],
              ['Sufi Cooking Oil 5L', '68 Cans', '18/day', '~3.7 Days', '10 Days'],
            ],
          },
          sqlQuery: `SELECT name, current_stock, daily_demand, ROUND(current_stock / daily_demand, 1) AS days_remaining
FROM trusted_inventory
WHERE (current_stock / daily_demand) < supplier_lead_time_days
ORDER BY days_remaining ASC;`,
          sourceDataset: 'trusted_inventory_realtime',
          explanation:
            'Grounded in supplier lead time matrix. Both products will exhaust before standard supplier replenishment can arrive.',
          reliabilityScore: 98,
        };
      }
      // Question 3: Declining customers / Orders kam
      else if (
        lower.includes('customer') ||
        lower.includes('orders kam') ||
        lower.includes('churn') ||
        lower.includes('declining')
      ) {
        response = {
          id: `msg-${Date.now()}-a`,
          sender: 'assistant',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          language: lower.includes('kam') ? 'Roman Urdu' : 'English',
          text: lower.includes('kam')
            ? 'Bismillah Mart (Lahore) aur Qadri General Store (Faisalabad) ke orders pichlay 30 din mein kafi kam ho chukay hain:'
            : 'Two key customer accounts exhibit significant order volume drops over the past 30 days:',
          tableData: {
            headers: ['Customer Name', 'City', 'Order Delta', '30d Spend', 'Status'],
            rows: [
              ['Bismillah Mart (Gulberg III)', 'Lahore', '-24.2%', 'PKR 2,950,000', 'At Risk (No dairy orders in 12d)'],
              ['Qadri General Store', 'Faisalabad', '-31.0%', 'PKR 1,480,000', 'At Risk (Frequency halved)'],
            ],
          },
          sqlQuery: `SELECT c.name, c.city, c.spend_trend_pct, c.total_spend_30d
FROM trusted_customers c
WHERE c.spend_trend_pct < -20.0
ORDER BY c.total_spend_30d DESC;`,
          sourceDataset: 'trusted_customers (PII Masking Active)',
          explanation:
            'Customer contact phone numbers are masked under Analyst role; customer trend is evaluated across 30-day moving windows.',
          reliabilityScore: 96,
        };
      }
      // Question 4: Duplicate revenue impact
      else if (lower.includes('duplicate') || lower.includes('impact') || lower.includes('inflation')) {
        response = {
          id: `msg-${Date.now()}-a`,
          sender: 'assistant',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          language: 'English',
          text: 'The Quality Engine identified 7 duplicate invoice lines in batch INV-2026-9281 originating from Lahore South Depot. This inflated reported sales by PKR 85,000 and skewed the Gourmet Cola forecast by +14%.',
          tableData: {
            headers: ['Invoice Line', 'Product', 'Reported Amount', 'Status', 'Audit Action'],
            rows: [
              ['INV-2026-9281 #L2', 'Gourmet Cola 1.5L', 'PKR 49,000', 'Quarantined Duplicate', 'REP-001 Pending'],
              ['INV-2026-9281 #L5', "Olper's Milk 1L", 'PKR 36,000', 'Quarantined Duplicate', 'REP-001 Pending'],
            ],
          },
          sqlQuery: `SELECT invoice_no, sku, COUNT(*) AS repeat_count, SUM(total_revenue) AS inflated_revenue
FROM raw_sales_staging
GROUP BY invoice_no, sku, quantity, unit_price
HAVING COUNT(*) > 1;`,
          sourceDataset: 'data_quality_anomalies_log',
          explanation:
            'Isolating duplicates prevents warehouse managers from issuing unnecessary emergency replenishment purchase orders.',
          reliabilityScore: 100,
        };
      }
      // Default conversational response
      else {
        response = {
          id: `msg-${Date.now()}-a`,
          sender: 'assistant',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          language: 'English',
          text: `Grounded analysis for query "${textToSend}": The active database currently tracks PKR ${(
            metrics.verifiedRevenuePKR / 1000000
          ).toFixed(2)}M in verified wholesale revenue across ${metrics.activeSKUs} SKUs with a composite data quality rating of 94.2%.`,
          tableData: {
            headers: ['Metric', 'Current Verified Value', 'Governance Status'],
            rows: [
              ['Verified Revenue', `PKR ${(metrics.verifiedRevenuePKR / 1000000).toFixed(2)}M`, 'Reconciled'],
              ['Data Quality Score', '94.2% Composite', 'Grade A'],
              ['Active Wholesale Accounts', `${customers.length} Accounts`, 'Normal Active'],
            ],
          },
          sqlQuery: `SELECT SUM(total_revenue) AS gross_verified, COUNT(DISTINCT sku) AS sku_count FROM trusted_sales WHERE status = 'Verified';`,
          sourceDataset: 'trusted_sales & trusted_inventory',
          explanation:
            'Grounded directly against warehouse PostgreSQL schema using verified, non-quarantined transactions.',
          reliabilityScore: 97,
        };
      }

      setMessages((prev) => [...prev, response]);
      setIsProcessing(false);
      addAuditLog('AI_QUERY_EXECUTED', 'AI Analytics Assistant', `Executed query: "${textToSend.substring(0, 50)}..."`);
    }, 700);
  };

  const handleClear = () => {
    setMessages([
      {
        id: 'msg-init-reset',
        sender: 'assistant',
        timestamp: 'Just now',
        text: 'Conversation history cleared. Ask me a question in English or Roman Urdu.',
      },
    ]);
  };

  return (
    <div className="space-y-4">
      {/* Top Banner */}
      <div className="p-4 bg-white border border-border rounded-lg shadow-panel flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <div className="p-2 rounded bg-teal text-white">
            <MessageSquareText className="w-4 h-4" />
          </div>
          <div>
            <h2 className="text-sm font-semibold text-navy">
              Conversational Analytics Console
            </h2>
            <p className="text-xs text-slate">
              Bilingual Natural Language Processing (English &amp; Roman Urdu) &middot; Schema-Grounded Read-Only SQL
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2 text-xs font-mono">
          <span className="px-2 py-1 bg-emerald-50 text-emerald-700 rounded border border-emerald-200 font-bold">
            English + Roman Urdu Supported
          </span>
          <button
            onClick={handleClear}
            className="p-1.5 text-slate hover:text-navy hover:bg-ivory rounded border border-border transition-colors"
            title="Clear Chat History"
          >
            <Trash2 className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Suggested Prompt Chips */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1 scrollbar-thin">
        <span className="text-[11px] font-mono text-slate uppercase shrink-0">Try Asking:</span>
        {SAMPLE_QUESTIONS.map((q, idx) => (
          <button
            key={idx}
            onClick={() => handleSend(q.text)}
            className="px-3 py-1 bg-white hover:bg-teal-light text-navy text-xs rounded border border-border hover:border-teal/40 transition-colors whitespace-nowrap shrink-0 font-medium shadow-panel"
          >
            <span className="text-[10px] text-teal font-mono mr-1.5">[{q.lang}]</span>
            <span>"{q.text}"</span>
          </button>
        ))}
      </div>

      {/* Main Chat Area */}
      <div className="bg-white border border-border rounded-lg shadow-panel flex flex-col h-[520px] overflow-hidden">
        {/* Messages Stream */}
        <div className="flex-1 overflow-y-auto p-4 sm:p-5 space-y-4">
          {messages.map((msg) => (
            <div
              key={msg.id}
              className={`flex flex-col ${
                msg.sender === 'user' ? 'items-end' : 'items-start'
              }`}
            >
              <div
                className={`max-w-2xl rounded-lg p-4 space-y-3 ${
                  msg.sender === 'user'
                    ? 'bg-navy text-white'
                    : 'bg-ivory/60 border border-border text-navy'
                }`}
              >
                {/* Header */}
                <div className="flex items-center justify-between gap-4 text-[10px] font-mono opacity-80 border-b border-white/10 pb-1">
                  <span>{msg.sender === 'user' ? 'You (Distributor)' : 'DistributionIQ AI'}</span>
                  <span>{msg.timestamp}</span>
                </div>

                {/* Text Body */}
                <p className="text-xs leading-relaxed">{msg.text}</p>

                {/* Embedded Data Table if present */}
                {msg.tableData && (
                  <div className="border border-border rounded bg-white overflow-hidden text-[11px] font-mono shadow-sm">
                    <table className="w-full text-left">
                      <thead className="bg-ivory text-slate border-b border-border">
                        <tr>
                          {msg.tableData.headers.map((h, i) => (
                            <th key={i} className="py-2 px-3">{h}</th>
                          ))}
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-border">
                        {msg.tableData.rows.map((row, rIdx) => (
                          <tr key={rIdx} className="hover:bg-ivory/40">
                            {row.map((cell, cIdx) => (
                              <td key={cIdx} className="py-2 px-3 text-navy font-semibold">
                                {cell}
                              </td>
                            ))}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}

                {/* Executed SQL Query Accordion / Badge */}
                {msg.sqlQuery && (
                  <div className="p-2.5 bg-navy-dark rounded border border-navy-light text-[11px] font-mono space-y-1">
                    <div className="flex items-center justify-between text-teal-light text-[10px]">
                      <span className="flex items-center gap-1">
                        <Code className="w-3 h-3" /> Grounded SQL Statement
                      </span>
                      <span className="text-emerald-400">SELECT Only (Read-Only Guard)</span>
                    </div>
                    <pre className="text-emerald-300 text-[10px] overflow-x-auto whitespace-pre-wrap">
                      {msg.sqlQuery}
                    </pre>
                  </div>
                )}

                {/* Lineage & Reliability Footnote */}
                {msg.sourceDataset && (
                  <div className="flex items-center justify-between text-[10px] font-mono text-slate pt-1 border-t border-border/40">
                    <span>Source: <strong>{msg.sourceDataset}</strong></span>
                    {msg.reliabilityScore && (
                      <span className="text-teal font-bold">Reliability: {msg.reliabilityScore}%</span>
                    )}
                  </div>
                )}
              </div>
            </div>
          ))}

          {isProcessing && (
            <div className="flex items-center gap-2 text-xs font-mono text-slate p-3 bg-ivory rounded max-w-xs animate-pulse">
              <Sparkles className="w-3.5 h-3.5 text-teal" />
              <span>Analyzing schema and executing read-only query...</span>
            </div>
          )}
        </div>

        {/* Input Bar */}
        <div className="p-3 bg-white border-t border-border flex items-center gap-2">
          <input
            type="text"
            placeholder="Type your question in English or Roman Urdu (e.g. 'Pichlay 30 din ki sales dikhao')..."
            value={inputText}
            onChange={(e) => setInputText(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && handleSend()}
            className="flex-1 px-3 py-2 text-xs border border-border rounded focus:outline-none focus:border-teal text-navy placeholder:text-slate bg-ivory/30"
          />
          <button
            onClick={() => handleSend()}
            disabled={!inputText.trim() || isProcessing}
            className="px-4 py-2 bg-teal hover:bg-teal-hover disabled:opacity-50 text-white text-xs font-semibold rounded flex items-center gap-1.5 transition-colors shadow-sm"
          >
            <span>Ask</span>
            <Send className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>
    </div>
  );
};

